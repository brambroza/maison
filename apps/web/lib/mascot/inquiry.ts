/** คำถามที่บัตเลอร์ยกขึ้นถาม */
export const INQUIRY = "แล้วท่านแวะมาทำอะไรหรือ";

/** ป้ายกำกับบนหัวป้ายคำพูดตอนถาม */
export const INQUIRY_KICKER = "บัตเลอร์ถาม";

/** คำตอบหนึ่งข้อ พร้อมคำโต้ที่บัตเลอร์เตรียมไว้แล้ว */
export type Answer = {
  /** รหัสอ้างอิง ใช้ภายในเท่านั้น ไม่แสดงต่อท่านสมาชิก */
  id: string;
  /** ถ้อยคำบนปุ่ม */
  label: string;
  /** คำโต้ของบัตเลอร์เมื่อท่านเลือกข้อนี้ */
  retort: string;
};

/** ตัวเลือกทั้งหมด เรียงตามลำดับที่แสดง */
export const ANSWERS: readonly Answer[] = [
  {
    id: "passing",
    label: "แค่ผ่านมา",
    retort: "ผ่านมาแล้วก็ผ่านไปได้เลย กระผมไม่ถือ",
  },
  {
    id: "bored",
    label: "มาแก้เบื่อ",
    retort: "สมาคมยินดีเป็นที่พึ่งลำดับสุดท้ายของท่าน",
  },
  {
    id: "unsure",
    label: "ไม่รู้เหมือนกัน",
    retort: "ท่านกับกระผมจึงมีสิ่งหนึ่งที่ตรงกัน",
  },
] as const;

/** คำโต้เมื่อท่านสมาชิกเลือกที่จะไม่ตอบ */
export const SILENCE_RETORT = "ท่านไม่ตอบก็ได้ กระผมจดไว้แล้วว่าไม่ตอบ";

/** คำโต้ของตัวเลือกที่ระบุ — คืน null เมื่อไม่มีตัวเลือกนั้น */
export function retortFor(id: string): string | null {
  return ANSWERS.find((answer) => answer.id === id)?.retort ?? null;
}
