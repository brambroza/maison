/**
 * สุ่มถ้อยคำหนึ่งบรรทัดตามอารมณ์ โดยเลี่ยงบรรทัดที่เพิ่งพูดไป
 *
 * @param mood อารมณ์ปัจจุบันของบัตเลอร์
 * @param previous บรรทัดล่าสุดที่พูดไปแล้ว ส่ง null ได้ถ้ายังไม่เคยพูด
 * @param random ฟังก์ชันสุ่ม แยกออกมาเป็นพารามิเตอร์เพื่อให้ทดสอบได้
 */
export function drawChatter(
  mood: ButlerMood,
  previous: string | null = null,
  random: () => number = Math.random,
): string {
  const all = CHATTER[mood];
  const choices = all.length > 1 ? all.filter((line) => line !== previous) : all;
  return choices[Math.floor(random() * choices.length) % choices.length];
}
